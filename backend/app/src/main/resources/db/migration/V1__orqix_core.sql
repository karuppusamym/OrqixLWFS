-- Orqix R0 application schema — reference DDL (contract).
-- Target: PostgreSQL 16 or later (uses UNIQUE ... NULLS NOT DISTINCT).
-- Applied by Flyway with defaultSchema = orqix, run only by the migration job as orqix_migrator.
-- Moved at ticket B01.4 from contracts/database/ to backend/app/src/main/resources/db/migration/. This copy is the
-- authoritative one; changes are new versioned migrations (expand/contract), never edits.
-- Flyway placeholder: ${app_role} = runtime DML role (e.g. orqix_app).
-- Spring Session tables are V2: copy schema-postgresql.sql verbatim from the pinned spring-session-jdbc jar.
-- Flowable tables are created by the migration job in schema 'flowable' (spike S-6), not by this file.
--
-- Conventions: UUIDs are generated by the application (UUIDv7). Every workspace-scoped table carries
-- workspace_id, and child rows reference parents through (workspace_id, id) so a cross-workspace link
-- cannot be stored even if service code is wrong.

-- ---------------------------------------------------------------------------------------------------
-- Identity, tenancy and access
-- ---------------------------------------------------------------------------------------------------

CREATE TABLE organization (
    id          uuid PRIMARY KEY,
    key         text NOT NULL UNIQUE CHECK (key ~ '^[a-z][a-z0-9-]{0,62}[a-z0-9]$'),
    name        text NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE workspace (
    id                            uuid PRIMARY KEY,
    organization_id               uuid NOT NULL REFERENCES organization (id),
    key                           text NOT NULL CHECK (key ~ '^[a-z][a-z0-9-]{0,62}[a-z0-9]$'),
    name                          text NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    engine_tenant_id              text NOT NULL UNIQUE,
    is_test                       boolean NOT NULL DEFAULT false,
    allow_self_approval_workflows boolean NOT NULL DEFAULT false,
    created_at                    timestamptz NOT NULL DEFAULT now(),
    archived_at                   timestamptz,
    UNIQUE (organization_id, key),
    CONSTRAINT workspace_self_approval_only_in_test CHECK (NOT allow_self_approval_workflows OR is_test)
);

CREATE TABLE subject (
    id                uuid PRIMARY KEY,
    issuer            text NOT NULL,
    external_subject  text NOT NULL,
    display_name      text NOT NULL CHECK (length(display_name) BETWEEN 1 AND 200),
    email             text,
    first_seen_at     timestamptz NOT NULL DEFAULT now(),
    last_login_at     timestamptz,
    disabled_at       timestamptz,
    UNIQUE (issuer, external_subject)
);

CREATE TABLE role_binding (
    id               uuid PRIMARY KEY,
    scope_type       text NOT NULL CHECK (scope_type IN ('platform', 'organization', 'workspace')),
    organization_id  uuid REFERENCES organization (id),
    workspace_id     uuid REFERENCES workspace (id),
    role             text NOT NULL CHECK (role IN ('PLATFORM_ADMIN', 'ORGANIZATION_ADMIN', 'WORKSPACE_ADMIN',
                                                   'WORKFLOW_DESIGNER', 'PUBLISHER', 'OPERATOR', 'VIEWER', 'APPROVER')),
    principal_type   text NOT NULL CHECK (principal_type IN ('subject', 'idpGroup')),
    principal_value  text NOT NULL CHECK (length(principal_value) BETWEEN 1 AND 256),
    source           text NOT NULL CHECK (source IN ('manual', 'seed', 'bootstrap')),
    created_by       uuid REFERENCES subject (id),
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT role_binding_scope CHECK (
        (scope_type = 'platform' AND organization_id IS NULL AND workspace_id IS NULL AND role = 'PLATFORM_ADMIN')
     OR (scope_type = 'organization' AND organization_id IS NOT NULL AND workspace_id IS NULL AND role = 'ORGANIZATION_ADMIN')
     OR (scope_type = 'workspace' AND organization_id IS NULL AND workspace_id IS NOT NULL
         AND role NOT IN ('PLATFORM_ADMIN', 'ORGANIZATION_ADMIN')))
);
CREATE UNIQUE INDEX role_binding_unique ON role_binding
    (scope_type, organization_id, workspace_id, role, principal_type, principal_value) NULLS NOT DISTINCT;
CREATE INDEX role_binding_by_workspace ON role_binding (workspace_id) WHERE workspace_id IS NOT NULL;
CREATE INDEX role_binding_by_principal ON role_binding (principal_type, principal_value);

CREATE TABLE workspace_group (
    id            uuid PRIMARY KEY,
    workspace_id  uuid NOT NULL REFERENCES workspace (id),
    key           text NOT NULL CHECK (key ~ '^[a-z][a-z0-9-]{0,62}[a-z0-9]$'),
    name          text NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    revision      integer NOT NULL DEFAULT 1,
    created_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, key),
    UNIQUE (workspace_id, id)
);

CREATE TABLE workspace_group_member (
    workspace_id     uuid NOT NULL,
    group_id         uuid NOT NULL,
    principal_type   text NOT NULL CHECK (principal_type IN ('subject', 'idpGroup')),
    principal_value  text NOT NULL CHECK (length(principal_value) BETWEEN 1 AND 256),
    created_by       uuid REFERENCES subject (id),
    created_at       timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (group_id, principal_type, principal_value),
    FOREIGN KEY (workspace_id, group_id) REFERENCES workspace_group (workspace_id, id) ON DELETE CASCADE
);
CREATE INDEX workspace_group_member_by_principal ON workspace_group_member (workspace_id, principal_type, principal_value);

-- ---------------------------------------------------------------------------------------------------
-- Workflow catalog, drafts and immutable releases
-- ---------------------------------------------------------------------------------------------------

CREATE TABLE workflow (
    id                 uuid PRIMARY KEY,
    workspace_id       uuid NOT NULL REFERENCES workspace (id),
    key                text NOT NULL CHECK (key ~ '^[a-z][a-z0-9-]{0,62}[a-z0-9]$'),
    name               text NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    description        text CHECK (length(description) <= 2000),
    owner_subject_id   uuid NOT NULL REFERENCES subject (id),
    draft_revision     integer NOT NULL DEFAULT 1 CHECK (draft_revision >= 1),
    active_release_id  uuid,
    version            integer NOT NULL DEFAULT 1,
    created_by         uuid NOT NULL REFERENCES subject (id),
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    archived_at        timestamptz,
    UNIQUE (workspace_id, key),
    UNIQUE (workspace_id, id)
);

CREATE TABLE workflow_draft_revision (
    workspace_id    uuid NOT NULL,
    workflow_id     uuid NOT NULL,
    revision        integer NOT NULL CHECK (revision >= 1),
    definition      jsonb NOT NULL,
    schema_version  text NOT NULL,
    saved_by        uuid NOT NULL REFERENCES subject (id),
    saved_at        timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (workflow_id, revision),
    FOREIGN KEY (workspace_id, workflow_id) REFERENCES workflow (workspace_id, id)
);

CREATE TABLE workflow_release (
    id                    uuid PRIMARY KEY,
    workspace_id          uuid NOT NULL,
    workflow_id           uuid NOT NULL,
    release_number        integer NOT NULL CHECK (release_number >= 1),
    draft_revision        integer NOT NULL,
    definition            jsonb NOT NULL,
    schema_version        text NOT NULL,
    source_hash           char(64) NOT NULL,
    semantic_hash         char(64) NOT NULL,
    compiler_version      text NOT NULL,
    manifest              jsonb NOT NULL,
    source_map            jsonb NOT NULL,
    warnings              jsonb NOT NULL DEFAULT '[]'::jsonb,
    engine_deployment_id  text NOT NULL,
    process_definition_id text NOT NULL UNIQUE,
    release_note          text CHECK (length(release_note) <= 1000),
    published_by          uuid NOT NULL REFERENCES subject (id),
    published_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workflow_id, release_number),
    UNIQUE (workspace_id, id),
    UNIQUE (workflow_id, id),
    FOREIGN KEY (workspace_id, workflow_id) REFERENCES workflow (workspace_id, id),
    FOREIGN KEY (workflow_id, draft_revision) REFERENCES workflow_draft_revision (workflow_id, revision)
);

ALTER TABLE workflow
    ADD CONSTRAINT workflow_active_release_belongs_to_workflow
    FOREIGN KEY (id, active_release_id) REFERENCES workflow_release (workflow_id, id);

CREATE TABLE release_artifact (
    release_id  uuid NOT NULL REFERENCES workflow_release (id),
    name        text NOT NULL CHECK (name ~ '^[A-Za-z0-9._/-]{1,200}$'),
    media_type  text NOT NULL,
    content     bytea NOT NULL,
    sha256      char(64) NOT NULL,
    PRIMARY KEY (release_id, name)
);

CREATE TABLE permission_grant (
    id               uuid PRIMARY KEY,
    workspace_id     uuid NOT NULL REFERENCES workspace (id),
    workflow_id      uuid,
    permission       text NOT NULL CHECK (permission IN ('workflow.start', 'connection.manage')),
    principal_type   text NOT NULL CHECK (principal_type IN ('subject', 'idpGroup')),
    principal_value  text NOT NULL CHECK (length(principal_value) BETWEEN 1 AND 256),
    created_by       uuid REFERENCES subject (id),
    created_at       timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (workspace_id, workflow_id) REFERENCES workflow (workspace_id, id),
    CONSTRAINT permission_grant_connection_is_workspace_wide CHECK (permission <> 'connection.manage' OR workflow_id IS NULL)
);
CREATE UNIQUE INDEX permission_grant_unique ON permission_grant
    (workspace_id, workflow_id, permission, principal_type, principal_value) NULLS NOT DISTINCT;

-- ---------------------------------------------------------------------------------------------------
-- Integrations
-- ---------------------------------------------------------------------------------------------------

CREATE TABLE connection_definition (
    id               uuid PRIMARY KEY,
    workspace_id     uuid NOT NULL REFERENCES workspace (id),
    key              text NOT NULL CHECK (key ~ '^[a-z][a-z0-9-]{0,62}[a-z0-9]$'),
    version          integer NOT NULL CHECK (version >= 1),
    definition       jsonb NOT NULL,
    definition_hash  char(64) NOT NULL,
    created_by       uuid NOT NULL REFERENCES subject (id),
    created_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, key, version)
);

CREATE TABLE connection_binding (
    workspace_id      uuid NOT NULL REFERENCES workspace (id),
    connection_key    text NOT NULL CHECK (connection_key ~ '^[a-z][a-z0-9-]{0,62}[a-z0-9]$'),
    base_url          text NOT NULL CHECK (base_url ~ '^https?://[^/?#@]+(/[^?#]*)?$'),
    auth_type         text NOT NULL CHECK (auth_type IN ('none', 'bearerToken', 'apiKeyHeader')),
    auth_header_name  text CHECK (auth_header_name ~ '^[A-Za-z][A-Za-z0-9-]{0,63}$'),
    secret_ref        text CHECK (secret_ref ~ '^[a-z0-9][a-z0-9-]{0,62}$'),
    enabled           boolean NOT NULL DEFAULT true,
    revision          integer NOT NULL DEFAULT 1,
    updated_by        uuid NOT NULL REFERENCES subject (id),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, connection_key),
    CONSTRAINT connection_binding_auth_shape CHECK (
        (auth_type = 'none' AND secret_ref IS NULL AND auth_header_name IS NULL)
     OR (auth_type = 'bearerToken' AND secret_ref IS NOT NULL AND auth_header_name IS NULL)
     OR (auth_type = 'apiKeyHeader' AND secret_ref IS NOT NULL AND auth_header_name IS NOT NULL))
);

-- ---------------------------------------------------------------------------------------------------
-- Runtime projections and records (Flowable remains authoritative for progression)
-- ---------------------------------------------------------------------------------------------------

CREATE TABLE workflow_run (
    id                          uuid PRIMARY KEY,
    workspace_id                uuid NOT NULL,
    workflow_id                 uuid NOT NULL,
    release_id                  uuid NOT NULL,
    engine_process_instance_id  text UNIQUE,
    business_key                text CHECK (length(business_key) BETWEEN 1 AND 100),
    initiator_subject_id        uuid NOT NULL REFERENCES subject (id),
    lifecycle                   text NOT NULL CHECK (lifecycle IN ('running', 'waiting', 'needsAttention', 'completed', 'cancelled')),
    outcome                     text,
    outcome_kind                text CHECK (outcome_kind IN ('success', 'rejected')),
    current_steps               jsonb NOT NULL DEFAULT '[]'::jsonb,
    attention                   jsonb,
    input                       jsonb NOT NULL,
    output                      jsonb,
    event_seq                   bigint NOT NULL DEFAULT 0,
    version                     integer NOT NULL DEFAULT 1,
    created_at                  timestamptz NOT NULL DEFAULT now(),
    updated_at                  timestamptz NOT NULL DEFAULT now(),
    ended_at                    timestamptz,
    UNIQUE (workspace_id, id),
    FOREIGN KEY (workspace_id, workflow_id) REFERENCES workflow (workspace_id, id),
    FOREIGN KEY (workflow_id, release_id) REFERENCES workflow_release (workflow_id, id),
    CONSTRAINT workflow_run_ended CHECK ((lifecycle IN ('completed', 'cancelled')) = (ended_at IS NOT NULL)),
    CONSTRAINT workflow_run_outcome_pair CHECK ((outcome IS NULL) = (outcome_kind IS NULL)),
    CONSTRAINT workflow_run_outcome_only_when_completed CHECK (outcome IS NULL OR lifecycle = 'completed'),
    CONSTRAINT workflow_run_attention_only_when_flagged CHECK ((attention IS NOT NULL) = (lifecycle = 'needsAttention'))
);
CREATE INDEX workflow_run_ws_created   ON workflow_run (workspace_id, created_at DESC, id DESC);
CREATE INDEX workflow_run_ws_initiator ON workflow_run (workspace_id, initiator_subject_id, created_at DESC, id DESC);
CREATE INDEX workflow_run_ws_workflow  ON workflow_run (workspace_id, workflow_id, created_at DESC, id DESC);
CREATE INDEX workflow_run_ws_attention ON workflow_run (workspace_id, updated_at DESC) WHERE lifecycle = 'needsAttention';
CREATE INDEX workflow_run_ws_bkey      ON workflow_run (workspace_id, business_key) WHERE business_key IS NOT NULL;
CREATE INDEX workflow_run_active       ON workflow_run (workflow_id) WHERE lifecycle IN ('running', 'waiting', 'needsAttention');

CREATE TABLE task_context (
    engine_task_id         text PRIMARY KEY,
    workspace_id           uuid NOT NULL,
    run_id                 uuid NOT NULL,
    node_id                text NOT NULL,
    label                  text NOT NULL,
    candidate_group_key    text NOT NULL,
    initiator_subject_id   uuid NOT NULL REFERENCES subject (id),
    self_approval_allowed  boolean NOT NULL DEFAULT false,
    assignee_subject_id    uuid REFERENCES subject (id),
    status                 text NOT NULL CHECK (status IN ('open', 'completed', 'cancelled')),
    version                integer NOT NULL DEFAULT 1,
    due_at                 timestamptz,
    created_at             timestamptz NOT NULL DEFAULT now(),
    claimed_at             timestamptz,
    ended_at               timestamptz,
    UNIQUE (workspace_id, engine_task_id),
    FOREIGN KEY (workspace_id, run_id) REFERENCES workflow_run (workspace_id, id),
    CONSTRAINT task_context_claim_pair CHECK ((assignee_subject_id IS NULL) = (claimed_at IS NULL)),
    CONSTRAINT task_context_ended CHECK ((status = 'open') = (ended_at IS NULL))
);
CREATE INDEX task_open_claimable ON task_context (workspace_id, candidate_group_key, created_at)
    WHERE status = 'open' AND assignee_subject_id IS NULL;
CREATE INDEX task_open_assigned  ON task_context (workspace_id, assignee_subject_id, created_at)
    WHERE status = 'open';
CREATE INDEX task_by_run         ON task_context (run_id);

CREATE TABLE task_decision (
    id                 uuid PRIMARY KEY,
    workspace_id       uuid NOT NULL,
    engine_task_id     text NOT NULL UNIQUE,
    run_id             uuid NOT NULL,
    node_id            text NOT NULL,
    actor_subject_id   uuid NOT NULL REFERENCES subject (id),
    action             text NOT NULL CHECK (action IN ('approve', 'reject')),
    reason             text CHECK (length(reason) <= 1000),
    comment            text CHECK (length(comment) <= 2000),
    policy_flags       jsonb NOT NULL DEFAULT '[]'::jsonb,
    decided_at         timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (workspace_id, engine_task_id) REFERENCES task_context (workspace_id, engine_task_id),
    FOREIGN KEY (workspace_id, run_id) REFERENCES workflow_run (workspace_id, id),
    CONSTRAINT task_decision_reject_reason CHECK (action <> 'reject' OR length(btrim(coalesce(reason, ''))) > 0)
);
CREATE INDEX task_decision_by_actor ON task_decision (workspace_id, actor_subject_id, decided_at DESC);
CREATE INDEX task_decision_by_run   ON task_decision (run_id, decided_at);

CREATE TABLE effect_journal (
    id                  uuid PRIMARY KEY,
    workspace_id        uuid NOT NULL,
    run_id              uuid NOT NULL,
    node_id             text NOT NULL,
    occurrence          integer NOT NULL DEFAULT 1 CHECK (occurrence >= 1),
    effect_key          text NOT NULL UNIQUE,
    connection_key      text NOT NULL,
    connection_version  integer NOT NULL,
    operation           text NOT NULL,
    effect_class        text NOT NULL CHECK (effect_class IN ('readOnly', 'idempotentWithKey', 'nonIdempotent')),
    request_hash        char(64) NOT NULL,
    state               text NOT NULL CHECK (state IN ('pending', 'inFlight', 'succeeded', 'retryableFailure',
                                                       'permanentFailure', 'unknown', 'notApplied')),
    attempts            integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    lease_owner         text,
    lease_until         timestamptz,
    last_http_status    integer,
    last_error_code     text,
    last_error_detail   text CHECK (length(last_error_detail) <= 2000),
    result              jsonb,
    remote_reference    text CHECK (length(remote_reference) <= 200),
    resolution          jsonb,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    UNIQUE (run_id, node_id, occurrence),
    UNIQUE (workspace_id, id),
    FOREIGN KEY (workspace_id, run_id) REFERENCES workflow_run (workspace_id, id),
    CONSTRAINT effect_succeeded_has_result CHECK (state <> 'succeeded' OR result IS NOT NULL),
    CONSTRAINT effect_inflight_has_lease CHECK (state <> 'inFlight' OR (lease_owner IS NOT NULL AND lease_until IS NOT NULL))
);
CREATE INDEX effect_by_run       ON effect_journal (run_id);
CREATE INDEX effect_needs_review ON effect_journal (workspace_id, updated_at DESC) WHERE state IN ('unknown', 'permanentFailure');

CREATE TABLE run_event (
    run_id            uuid NOT NULL,
    seq               bigint NOT NULL CHECK (seq >= 1),
    workspace_id      uuid NOT NULL,
    type              text NOT NULL CHECK (type ~ '^[A-Z][A-Z_]{2,63}$'),
    node_id           text,
    actor_subject_id  uuid REFERENCES subject (id),
    occurred_at       timestamptz NOT NULL DEFAULT now(),
    data              jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (run_id, seq),
    FOREIGN KEY (workspace_id, run_id) REFERENCES workflow_run (workspace_id, id)
);

CREATE TABLE notification (
    id                    uuid PRIMARY KEY,
    workspace_id          uuid NOT NULL REFERENCES workspace (id),
    recipient_subject_id  uuid NOT NULL REFERENCES subject (id),
    run_id                uuid,
    kind                  text NOT NULL CHECK (kind IN ('workflowMessage', 'runAttention')),
    dedup_key             text NOT NULL UNIQUE,
    message               text NOT NULL CHECK (length(message) BETWEEN 1 AND 500),
    created_at            timestamptz NOT NULL DEFAULT now(),
    read_at               timestamptz,
    FOREIGN KEY (workspace_id, run_id) REFERENCES workflow_run (workspace_id, id)
);
CREATE INDEX notification_inbox  ON notification (workspace_id, recipient_subject_id, created_at DESC, id DESC);
CREATE INDEX notification_unread ON notification (workspace_id, recipient_subject_id) WHERE read_at IS NULL;

-- ---------------------------------------------------------------------------------------------------
-- Cross-cutting: audit and idempotency
-- ---------------------------------------------------------------------------------------------------

CREATE TABLE audit_event (
    id                uuid PRIMARY KEY,
    workspace_id      uuid REFERENCES workspace (id),
    actor_type        text NOT NULL CHECK (actor_type IN ('user', 'service', 'system')),
    actor_subject_id  uuid REFERENCES subject (id),
    action            text NOT NULL CHECK (action ~ '^[a-z]+(\.[a-z-]+)+$'),
    resource_type     text NOT NULL,
    resource_id       text,
    outcome           text NOT NULL CHECK (outcome IN ('success', 'denied', 'failed')),
    correlation_id    text NOT NULL,
    occurred_at       timestamptz NOT NULL DEFAULT now(),
    metadata          jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT audit_user_has_subject CHECK (actor_type <> 'user' OR actor_subject_id IS NOT NULL)
);
CREATE INDEX audit_by_workspace ON audit_event (workspace_id, occurred_at DESC);
CREATE INDEX audit_by_resource  ON audit_event (resource_type, resource_id, occurred_at DESC);

CREATE TABLE idempotency_record (
    workspace_id          uuid NOT NULL REFERENCES workspace (id),
    principal_subject_id  uuid NOT NULL REFERENCES subject (id),
    operation             text NOT NULL,
    idem_key              text NOT NULL CHECK (idem_key ~ '^[A-Za-z0-9._:-]{8,128}$'),
    request_hash          char(64) NOT NULL,
    resource_type         text,
    resource_id           text,
    response_status       integer,
    created_at            timestamptz NOT NULL DEFAULT now(),
    expires_at            timestamptz NOT NULL,
    PRIMARY KEY (workspace_id, principal_subject_id, operation, idem_key),
    CONSTRAINT idempotency_completed_shape CHECK ((resource_id IS NULL) = (response_status IS NULL))
);
CREATE INDEX idempotency_expiry ON idempotency_record (expires_at);

