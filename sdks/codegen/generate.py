#!/usr/bin/env python3
"""Generates the typed models and operation tables of the Orqix SDKs from contracts/openapi.yaml (CG-K02).

Scope: the machine-client surface, which is what an SDK can call with a bearer token or a callback token. It is the
list of operations the server's machine security chain admits (SecurityConfiguration.machineChain) plus the two
callback-token operations. Everything else needs a browser session; the TypeScript SDK still types it through the
full openapi-typescript output.

Outputs (committed; ``--check`` fails when they are stale):

  sdks/java/orqix-client/src/main/java/com/orqix/sdk/model/*.java   records and enum-constant classes
  sdks/java/orqix-client/src/main/java/com/orqix/sdk/OrqixOperation.java
  sdks/dotnet/src/Orqix.Client/Generated/Models.cs
  sdks/dotnet/src/Orqix.Client/Generated/OrqixOperations.cs
  sdks/typescript/src/generated/operations.ts

Compatibility choices (docs/api-compatibility.md, "SDKs"):
  * Unknown response fields are ignored, so additive server changes never break an SDK.
  * Enums are plain strings with generated constants, so a new enum value never fails deserialization.
  * date-time fields are OffsetDateTime / DateTimeOffset; numbers are BigDecimal / decimal (the server's numerics).

    python sdks/codegen/generate.py           # write
    python sdks/codegen/generate.py --check   # exit 1 when a committed file differs
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]
OPENAPI = ROOT / "contracts" / "openapi.yaml"

# Bearer operations of SecurityConfiguration.machineChain, then the callback-token operations (security: []).
MACHINE_OPERATIONS = [
    "startRun", "getRun", "listRunEvents", "sendMessage",
    "fetchExternalJobs", "extendExternalJobLock", "completeExternalJob", "failExternalJob",
    "awaitExternalJobCallback", "completeExternalJobCallback", "failExternalJobCallback",
    "issueCallbackToken",
    "pollCallbackWait", "resumeCallbackWait",
]

JAVA_PACKAGE = "com.orqix.sdk"
JAVA_MODEL_DIR = ROOT / "sdks/java/orqix-client/src/main/java/com/orqix/sdk/model"
JAVA_OPERATIONS = ROOT / "sdks/java/orqix-client/src/main/java/com/orqix/sdk/OrqixOperation.java"
DOTNET_MODELS = ROOT / "sdks/dotnet/src/Orqix.Client/Generated/Models.cs"
DOTNET_OPERATIONS = ROOT / "sdks/dotnet/src/Orqix.Client/Generated/OrqixOperations.cs"
TS_OPERATIONS = ROOT / "sdks/typescript/src/generated/operations.ts"
HEADER = "Generated by sdks/codegen/generate.py from contracts/openapi.yaml. Do not edit."

JAVA_KEYWORDS = set("""abstract assert boolean break byte case catch char class const continue default do double else enum
extends final finally float for goto if implements import instanceof int interface long native new package private
protected public return short static strictfp super switch synchronized this throw throws transient try void volatile
while record yield var""".split())


@dataclass
class Type:
    kind: str  # string, datetime, integer, number, boolean, map, list, record, any
    ref: str | None = None
    item: "Type | None" = None
    nullable: bool = False

    def with_null(self) -> "Type":
        return Type(self.kind, self.ref, self.item, True)


@dataclass
class Prop:
    name: str
    type: Type
    required: bool
    description: str = ""


@dataclass
class Record:
    name: str
    source: str
    description: str
    props: list[Prop] = field(default_factory=list)


@dataclass
class Operation:
    operation_id: str
    method: str
    path: str
    path_params: list[str]
    query_params: list[tuple[str, Type]]
    idempotency_key: bool
    credential: str  # bearer or callbackToken
    request: str | None
    response: str | None
    success: list[str]
    summary: str


class Model:
    def __init__(self, document: dict[str, Any]):
        self.document = document
        self.schemas: dict[str, Any] = document["components"]["schemas"]
        self.records: dict[str, Record] = {}
        self.enums: dict[str, list[str]] = {}
        self.operations: list[Operation] = []

    # ---------------------------------------------------------------- types

    def type_of(self, schema: Any, context: str) -> Type:
        if not isinstance(schema, dict):
            return Type("any")
        if "$ref" in schema:
            name = schema["$ref"].rsplit("/", 1)[1]
            target = self.schemas[name]
            if self._is_record(target):
                self.record(name, target)
                return Type("record", ref=name)
            if target.get("enum") and target.get("type") == "string":
                self.enums[name] = [str(v) for v in target["enum"]]
            return self.type_of(target, name)
        if "allOf" in schema:
            if len(schema["allOf"]) == 1:
                return self.type_of(schema["allOf"][0], context)
            raise SystemExit(f"{context}: allOf with several parts is only supported for a whole schema")
        alternatives = schema.get("oneOf") or schema.get("anyOf")
        if alternatives:
            others = [a for a in alternatives if a != {"type": "null"}]
            if len(others) == 1:
                inner = self.type_of(others[0], context)
                return inner.with_null() if len(others) < len(alternatives) else inner
            return Type("any", nullable=len(others) < len(alternatives))
        declared = schema.get("type")
        nullable = False
        if isinstance(declared, list):
            nullable = "null" in declared
            rest = [t for t in declared if t != "null"]
            declared = rest[0] if len(rest) == 1 else None
            if declared is None:
                return Type("any", nullable=nullable)
        result: Type
        if declared == "object" or (declared is None and "properties" in schema):
            if schema.get("properties"):
                self.record(context, schema)
                result = Type("record", ref=context)
            else:
                extra = schema.get("additionalProperties")
                value = self.type_of(extra, context + "Value") if isinstance(extra, dict) else Type("any")
                result = Type("map", item=value)
        elif declared == "array":
            result = Type("list", item=self.type_of(schema.get("items", {}), context + "Item"))
        elif declared == "string":
            result = Type("datetime" if schema.get("format") == "date-time" else "string")
        elif declared in ("integer", "number", "boolean"):
            result = Type(declared)
        else:
            result = Type("any")
        return result.with_null() if nullable else result

    @staticmethod
    def _is_record(schema: dict[str, Any]) -> bool:
        return bool(schema.get("properties")) or len(schema.get("allOf", [])) > 1

    def record(self, name: str, schema: dict[str, Any]) -> Record:
        if name in self.records:
            return self.records[name]
        record = Record(name, name if name in self.schemas else "inline", _one_line(schema.get("description", "")))
        self.records[name] = record  # registered first: a schema may refer to itself
        parts = schema["allOf"] if len(schema.get("allOf", [])) > 1 else [schema]
        seen: set[str] = set()
        for part in parts:
            if "$ref" in part:
                base_name = part["$ref"].rsplit("/", 1)[1]
                base = self.record(base_name, self.schemas[base_name])
                props = base.props
            else:
                required = set(part.get("required", []))
                props = [Prop(str(prop), self.type_of(sub, name + _pascal(str(prop))), str(prop) in required,
                              _one_line((sub or {}).get("description", "")))
                         for prop, sub in (part.get("properties") or {}).items()]
            for prop in props:
                if prop.name not in seen:
                    seen.add(prop.name)
                    record.props.append(prop)
        return record

    # ---------------------------------------------------------------- operations

    def load_operations(self) -> None:
        index: dict[str, tuple[str, str, dict, list]] = {}
        for path, item in self.document["paths"].items():
            for method in ("get", "post", "put", "delete", "patch"):
                op = item.get(method)
                if isinstance(op, dict) and op.get("operationId"):
                    index[op["operationId"]] = (method.upper(), path, op, item.get("parameters", []))
        for operation_id in MACHINE_OPERATIONS:
            if operation_id not in index:
                raise SystemExit(f"operation {operation_id} is not in contracts/openapi.yaml")
            method, path, op, shared = index[operation_id]
            params = [self._param(p) for p in shared + op.get("parameters", [])]
            query = [(p["name"], self.type_of(p.get("schema", {}), _pascal(operation_id) + _pascal(p["name"])))
                     for p in params if p["in"] == "query"]
            headers = {p["name"] for p in params if p["in"] == "header"}
            request = None
            body = op.get("requestBody")
            if body:
                schema = body["content"]["application/json"]["schema"]
                request = self._named(schema, _pascal(operation_id) + "Request")
            response = None
            success = sorted(str(s) for s in op["responses"] if str(s).startswith("2"))
            for status in success:
                content = (op["responses"][status] or {}).get("content") or {}
                if "application/json" in content:
                    response = self._named(content["application/json"]["schema"], _pascal(operation_id) + "Response")
                    break
            credential = "callbackToken" if op.get("security") == [] else "bearer"
            self.operations.append(Operation(
                operation_id, method, path, re.findall(r"{([^}]+)}", path), query,
                "Idempotency-Key" in headers, credential, request, response, success,
                _one_line(op.get("summary", ""))))

    def _param(self, param: dict[str, Any]) -> dict[str, Any]:
        if "$ref" in param:
            return self.document["components"]["parameters"][param["$ref"].rsplit("/", 1)[1]]
        return param

    def _named(self, schema: dict[str, Any], fallback: str) -> str:
        t = self.type_of(schema, fallback)
        if t.kind != "record" or t.ref is None:
            raise SystemExit(f"{fallback}: the SDK expects an object body")
        return t.ref


def _pascal(text: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", text)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def _constant(text: str) -> str:
    snake = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", text)
    snake = re.sub(r"[^A-Za-z0-9]+", "_", snake).strip("_").upper()
    return snake if not snake[:1].isdigit() else "_" + snake


def _one_line(text: str) -> str:
    return " ".join(str(text).split())


def _doc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("*/", "*&#47;") \
        .replace("@", "&#64;")


# -------------------------------------------------------------------- Java


def java_type(t: Type) -> str:
    match t.kind:
        case "string":
            return "String"
        case "datetime":
            return "OffsetDateTime"
        case "integer":
            return "Long"
        case "number":
            return "BigDecimal"
        case "boolean":
            return "Boolean"
        case "map":
            return f"Map<String, {java_type(t.item) if t.item and t.item.kind != 'any' else 'Object'}>"
        case "list":
            return f"List<{java_type(t.item)}>"
        case "record":
            return t.ref or "Object"
    return "Object"


def java_record(record: Record) -> str:
    fields = []
    for prop in record.props:
        name = prop.name + "_" if prop.name in JAVA_KEYWORDS else prop.name
        fields.append((prop, name, java_type(prop.type)))
    used = " ".join(t for _, _, t in fields)
    imports = ["com.fasterxml.jackson.annotation.JsonIgnoreProperties",
               "com.fasterxml.jackson.annotation.JsonInclude",
               "com.fasterxml.jackson.annotation.JsonProperty"]
    for token, imp in (("BigDecimal", "java.math.BigDecimal"), ("OffsetDateTime", "java.time.OffsetDateTime"),
                       ("List<", "java.util.List"), ("Map<", "java.util.Map")):
        if token in used:
            imports.append(imp)
    source = f"components.schemas.{record.name}" if record.source != "inline" else "an inline schema"
    lines = [f"// {HEADER}", f"package {JAVA_PACKAGE}.model;", ""]
    lines += [f"import {imp};" for imp in imports]
    lines += ["", "/**"]
    if record.description:
        lines.append(f" * {_doc(record.description)}")
        lines.append(" *")
    lines.append(f" * <p>From {source} of the Orqix API. Unknown fields are ignored; new optional components may be "
                 "added in a minor SDK release.")
    for prop, name, _ in fields:
        text = _doc(prop.description) if prop.description else ("required" if prop.required else "optional")
        if prop.type.nullable:
            text += " (may be null)"
        lines.append(f" * @param {name} {text}")
    lines += [" */", "@JsonIgnoreProperties(ignoreUnknown = true)", "@JsonInclude(JsonInclude.Include.NON_NULL)",
              f"public record {record.name}("]
    rendered = [f"        @JsonProperty(\"{prop.name}\") {jt} {name}" for prop, name, jt in fields]
    lines.append(",\n".join(rendered) + ") {")
    lines += ["}", ""]
    return "\n".join(lines)


def java_enum(name: str, values: list[str]) -> str:
    lines = [f"// {HEADER}", f"package {JAVA_PACKAGE}.model;", "", "/**",
             f" * Values of components.schemas.{name}. Fields of this kind are plain strings: a value added by a later",
             " * server release is passed through instead of failing.", " */",
             f"public final class {name} {{", ""]
    for value in values:
        lines.append(f"    public static final String {_constant(value)} = \"{value}\";")
    lines += ["", f"    private {name}() {{", "    }", "}", ""]
    return "\n".join(lines)


def java_operations(model: Model) -> str:
    lines = [f"// {HEADER}", f"package {JAVA_PACKAGE};", "", "import java.net.URLEncoder;",
             "import java.nio.charset.StandardCharsets;", "import java.util.List;", "", "/**",
             " * The operations of the Orqix API that machine clients may call: with a bearer token (the server's machine",
             " * security chain) or with a callback token.", " */", "public enum OrqixOperation {"]
    rendered = []
    for op in model.operations:
        params = ", ".join(f'"{p}"' for p in op.path_params)
        rendered.append(f"    /** {_doc(op.summary or op.operation_id)} */\n"
                        f"    {_constant(op.operation_id)}(\"{op.operation_id}\", \"{op.method}\", \"{op.path}\", "
                        f"List.of({params}), {str(op.idempotency_key).lower()}, "
                        f"{'Credential.CALLBACK_TOKEN' if op.credential == 'callbackToken' else 'Credential.BEARER'})")
    lines.append(",\n".join(rendered) + ";")
    lines += ["",
              "    /** How an operation authenticates. */",
              "    public enum Credential {",
              "        /** {@code Authorization: Bearer} with a machine identity's access token. */",
              "        BEARER,",
              "        /** {@code X-Orqix-Callback-Token}: the token is the credential, no bearer token is sent. */",
              "        CALLBACK_TOKEN",
              "    }",
              "",
              "    private final String operationId;",
              "    private final String method;",
              "    private final String pathTemplate;",
              "    private final List<String> pathParameters;",
              "    private final boolean idempotencyKeyRequired;",
              "    private final Credential credential;",
              "",
              "    OrqixOperation(String operationId, String method, String pathTemplate, List<String> pathParameters,",
              "            boolean idempotencyKeyRequired, Credential credential) {",
              "        this.operationId = operationId;",
              "        this.method = method;",
              "        this.pathTemplate = pathTemplate;",
              "        this.pathParameters = pathParameters;",
              "        this.idempotencyKeyRequired = idempotencyKeyRequired;",
              "        this.credential = credential;",
              "    }",
              "",
              "    public String operationId() {", "        return operationId;", "    }", "",
              "    public String method() {", "        return method;", "    }", "",
              "    public String pathTemplate() {", "        return pathTemplate;", "    }", "",
              "    public List<String> pathParameters() {", "        return pathParameters;", "    }", "",
              "    public boolean idempotencyKeyRequired() {", "        return idempotencyKeyRequired;", "    }", "",
              "    public Credential credential() {", "        return credential;", "    }", "",
              "    /** The path with each parameter, in template order, URL-encoded. */",
              "    public String path(String... values) {",
              "        if (values.length != pathParameters.size()) {",
              "            throw new IllegalArgumentException(operationId + \" takes \" + pathParameters + \"\");",
              "        }",
              "        String path = pathTemplate;",
              "        for (int i = 0; i < values.length; i++) {",
              "            String encoded = URLEncoder.encode(values[i], StandardCharsets.UTF_8).replace(\"+\", \"%20\");",
              "            path = path.replace(\"{\" + pathParameters.get(i) + \"}\", encoded);",
              "        }",
              "        return path;",
              "    }",
              "}", ""]
    return "\n".join(lines)


# -------------------------------------------------------------------- .NET


def cs_type(t: Type) -> str:
    match t.kind:
        case "string":
            base = "string"
        case "datetime":
            base = "DateTimeOffset"
        case "integer":
            base = "long"
        case "number":
            base = "decimal"
        case "boolean":
            base = "bool"
        case "map":
            value = cs_type(t.item) if t.item and t.item.kind != "any" else "object?"
            base = f"Dictionary<string, {value}>"
        case "list":
            base = f"List<{cs_type(t.item)}>"
        case "record":
            base = t.ref or "object"
        case _:
            base = "object"
    return base


def _xml(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def dotnet_models(model: Model) -> str:
    lines = [f"// {HEADER}", "#nullable enable", "#pragma warning disable CS1591 // generated: members without a contract description", "using System;", "using System.Collections.Generic;",
             "using System.Text.Json.Serialization;", "", "namespace Orqix.Client.Models;", ""]
    for name, values in sorted(model.enums.items()):
        lines += [f"/// <summary>Values of components.schemas.{name}. Fields of this kind are plain strings, so a value "
                  "added by a later server release is passed through.</summary>",
                  f"public static class {name}", "{"]
        lines += [f"    public const string {_pascal(v.lower() if v.isupper() else v)} = \"{v}\";" for v in values]
        lines += ["}", ""]
    for name in sorted(model.records):
        record = model.records[name]
        summary = record.description or (f"components.schemas.{name}" if record.source != "inline" else name)
        lines += [f"/// <summary>{_xml(summary)}</summary>",
                  "/// <remarks>Unknown fields are ignored; new optional properties may be added in a minor SDK "
                  "release.</remarks>",
                  f"public sealed record {name}", "{"]
        for prop in record.props:
            member = _pascal(prop.name)
            if member == name:
                member += "Value"
            base = cs_type(prop.type)
            non_null = prop.required and not prop.type.nullable
            reference = prop.type.kind not in ("datetime", "integer", "number", "boolean")
            if prop.description:
                lines.append(f"    /// <summary>{_xml(prop.description)}</summary>")
            lines.append(f"    [JsonPropertyName(\"{prop.name}\")]")
            if non_null:
                lines.append(f"    public {base} {member} {{ get; init; }}{' = default!;' if reference else ''}")
            else:
                lines.append(f"    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]")
                lines.append(f"    public {base}? {member} {{ get; init; }}")
        lines += ["}", ""]
    return "\n".join(lines)


def dotnet_operations(model: Model) -> str:
    lines = [f"// {HEADER}", "#nullable enable", "#pragma warning disable CS1591 // generated: members without a contract description", "using System;", "using System.Collections.Generic;", "",
             "namespace Orqix.Client;", "",
             "/// <summary>How an operation authenticates.</summary>",
             "public enum OrqixCredential",
             "{",
             "    /// <summary><c>Authorization: Bearer</c> with a machine identity's access token.</summary>",
             "    Bearer,",
             "    /// <summary><c>X-Orqix-Callback-Token</c>: the token is the credential.</summary>",
             "    CallbackToken,",
             "}",
             "",
             "/// <summary>An operation of the Orqix API that machine clients may call.</summary>",
             "public sealed record OrqixOperation(string OperationId, string Method, string PathTemplate,",
             "    IReadOnlyList<string> PathParameters, bool IdempotencyKeyRequired, OrqixCredential Credential)",
             "{",
             "    /// <summary>The path with each parameter, in template order, URL-encoded.</summary>",
             "    public string Path(params string[] values)",
             "    {",
             "        if (values.Length != PathParameters.Count)",
             "        {",
             "            throw new ArgumentException($\"{OperationId} takes {string.Join(\", \", PathParameters)}\");",
             "        }",
             "        var path = PathTemplate;",
             "        for (var i = 0; i < values.Length; i++)",
             "        {",
             "            path = path.Replace(\"{\" + PathParameters[i] + \"}\", Uri.EscapeDataString(values[i]));",
             "        }",
             "        return path;",
             "    }",
             "}",
             "",
             "/// <summary>The machine-client operations: bearer operations of the server's machine security chain and the",
             "/// callback-token operations.</summary>",
             "public static class OrqixOperations",
             "{"]
    for op in model.operations:
        params = ", ".join(f'"{p}"' for p in op.path_params)
        credential = "OrqixCredential.CallbackToken" if op.credential == "callbackToken" else "OrqixCredential.Bearer"
        lines.append(f"    /// <summary>{_xml(op.summary or op.operation_id)}</summary>")
        lines.append(f"    public static readonly OrqixOperation {_pascal(op.operation_id)} = new(\"{op.operation_id}\", "
                     f"\"{op.method}\", \"{op.path}\", new[] {{ {params} }}, {str(op.idempotency_key).lower()}, "
                     f"{credential});")
    names = ", ".join(_pascal(op.operation_id) for op in model.operations)
    lines += ["", "    /// <summary>Every machine-client operation, in contract order.</summary>",
              f"    public static readonly IReadOnlyList<OrqixOperation> All = new[] {{ {names} }};", "}", ""]
    return "\n".join(lines)


# -------------------------------------------------------------------- TypeScript


def ts_operations(model: Model) -> str:
    lines = [f"// {HEADER}", "",
             "/** The operations machine clients may call: with a bearer token or with a callback token. */",
             "export const machineOperations = {"]
    for op in model.operations:
        params = ", ".join(f"'{p}'" for p in op.path_params)
        lines.append(f"  {op.operation_id}: {{ method: '{op.method}', path: '{op.path}', pathParameters: [{params}], "
                     f"idempotencyKeyRequired: {str(op.idempotency_key).lower()}, credential: '{op.credential}' }},")
    lines += ["} as const", "", "export type MachineOperationId = keyof typeof machineOperations", ""]
    return "\n".join(lines)


# -------------------------------------------------------------------- main


def outputs(document: dict[str, Any]) -> dict[Path, str]:
    model = Model(document)
    model.load_operations()
    files: dict[Path, str] = {}
    for name, record in sorted(model.records.items()):
        files[JAVA_MODEL_DIR / f"{name}.java"] = java_record(record)
    for name, values in sorted(model.enums.items()):
        files[JAVA_MODEL_DIR / f"{name}.java"] = java_enum(name, values)
    files[JAVA_OPERATIONS] = java_operations(model)
    files[DOTNET_MODELS] = dotnet_models(model)
    files[DOTNET_OPERATIONS] = dotnet_operations(model)
    files[TS_OPERATIONS] = ts_operations(model)
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the SDK models and operation tables")
    parser.add_argument("--check", action="store_true", help="fail when a committed file is stale")
    args = parser.parse_args(argv)
    with OPENAPI.open(encoding="utf-8") as handle:
        document = yaml.safe_load(handle)
    files = outputs(document)
    stale = []
    existing_models = set(JAVA_MODEL_DIR.glob("*.java")) if JAVA_MODEL_DIR.exists() else set()
    for path, text in files.items():
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
        if current != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    orphans = sorted(existing_models - set(files))
    for orphan in orphans:
        stale.append(orphan)
        if not args.check:
            orphan.unlink()
    if args.check:
        if stale:
            for path in stale:
                print(f"stale: {path.relative_to(ROOT).as_posix()}")
            print("Run python sdks/codegen/generate.py and commit the result.")
            return 1
        print(f"SDK code is current ({len(files)} generated files).")
        return 0
    print(f"Wrote {len(stale)} of {len(files)} generated files" + (f", removed {len(orphans)}" if orphans else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
