import { expect, test } from '../support/fixtures'
import { MOCK } from '../support/env'
import { apiGet, selectStep, workspaceId } from '../support/app'
import { apiSend, createWorkflow, publish, uniq } from '../support/api'
import { expectNoSeriousViolations } from '../support/axe'

test('a pinned reusable approval view reaches an authorized task with mobile accessible decision controls', async ({ sessions }) => {
  test.setTimeout(180_000)
  if (MOCK) await sessions.mockCall('reset', { demo: true })
  let page = await sessions.as('dana.designer')
  const ws = await workspaceId(page)
  const workflow = await createWorkflow(page, ws, uniq('Approval view'))
  const draft = await apiGet<{ definition: { inputSchema: { required: string[]; properties: Record<string, { type: string; enum?: string[] }> } } }>(page, `/workspaces/${ws}/workflows/${workflow.id}/draft`)
  const view = { schemaVersion: 1, kind: 'approval', sections: [{ id: 'review', label: 'Shared purchase review', columns: 2,
    fields: Object.entries(draft.definition.inputSchema.properties).map(([key, property]) => ({ id: key, label: `Review ${key}`, binding: `request.${key}`, type: property.enum ? 'choice' : property.type === 'number' ? 'number' : 'text', required: draft.definition.inputSchema.required.includes(key), ...(property.enum ? { options: property.enum.map(value => ({ value, label: value })) } : {}) })) }], actions: [{ id: 'yes', type: 'approve', label: 'Authorize purchase' }, { id: 'no', type: 'reject', label: 'Decline purchase' }] }
  const created = await apiSend<{ id: string }>(page, 'POST', `/workspaces/${ws}/views`, { name: uniq('Shared approval'), definition: view })
  expect(created.status).toBe(201)
  page = await sessions.as('paul.publisher')
  expect((await apiSend(page, 'POST', `/workspaces/${ws}/views/${created.body.id}/publish`, { expectedRevision: 1 })).status).toBe(200)
  page = await sessions.as('dana.designer')
  await page.goto(`/w/${ws}/workflows/${workflow.id}/edit`)
  await page.getByRole('tab', { name: 'Steps', exact: true }).click()
  await selectStep(page, 'manager')
  await page.getByRole('button', { name: 'Choose approval view' }).click()
  await page.getByLabel('Published approval view').selectOption(created.body.id)
  await page.getByRole('button', { name: 'Apply approval view', exact: true }).click()
  await expect(page.getByText(`Pinned approval view ${created.body.id}, version 1`)).toBeVisible()
  await expect(page.getByTestId('save-state')).toContainText('Saved')
  await expectNoSeriousViolations(page, 'Pinned approval view authoring')
  page = await sessions.as('paul.publisher'); await publish(page, ws, workflow.id)
  page = await sessions.as('rhea.requester')
  const title = uniq('Approval context')
  const started = await apiSend<{ id: string }>(page, 'POST', `/workspaces/${ws}/runs`, { workflowId: workflow.id, input: { title, purpose: 'Verify immutable review layout', costCenter: 'OPS', amount: 100 } })
  expect(started.status).toBe(201)
  const run = await apiGet<{ tasks: Array<{ id: string; nodeId: string }> }>(page, `/workspaces/${ws}/runs/${started.body.id}`)
  const task = run.tasks.find(item => item.nodeId === 'manager')
  expect(task).toBeTruthy()
  page = await sessions.as('max.manager')
  await page.goto(`/w/${ws}/tasks/${task!.id}?view=claimable`)
  await expect(page.getByRole('region', { name: 'Shared purchase review' })).toContainText(title)
  await expect(page.getByRole('button', { name: 'Authorize purchase' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Claim task', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Authorize purchase' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expectNoSeriousViolations(page, 'Pinned approval mobile task')
  await page.getByRole('button', { name: 'Decline purchase', exact: true }).click()
  await expect(page.getByText('Add a reason so the requester knows what to change', { exact: true })).toBeVisible()
  await page.getByLabel('Comment', { exact: false }).fill('Outside the reviewed budget')
  await page.getByRole('button', { name: 'Decline purchase', exact: true }).click()
  await expect(page.getByTestId('task-banner')).toContainText('You rejected')
  await page.reload()
  await expect(page.getByRole('region', { name: 'Shared purchase review' })).toContainText(title)
  await expect(page.getByRole('button', { name: 'Decline purchase' })).toHaveCount(0)
  await expectNoSeriousViolations(page, 'Pinned approval completed task')
})
