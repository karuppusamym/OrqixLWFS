import { readFile } from 'node:fs/promises'
import { expect,test } from '../support/fixtures'
import { MOCK } from '../support/env'
import { workspaceId } from '../support/app'
import { uniq } from '../support/api'
import { expectNoSeriousViolations } from '../support/axe'

test('a visually authored model executes required manual work and achieves its milestone',async({sessions})=>{
  test.skip(MOCK,'Verifies generated CMMN against the real case engine.')
  test.setTimeout(180_000)
  let page=await sessions.as('dana.designer')
  const ws=await workspaceId(page),key=uniq('visual-case')
  await page.goto(`/w/${ws}/cases`)
  await page.getByLabel('Key',{exact:true}).fill(key)
  await page.getByLabel('Name',{exact:true}).fill(key)
  await page.getByRole('button',{name:'Build a case model',exact:true}).click()
  await page.getByRole('button',{name:'Form view',exact:true}).click()
  await page.getByLabel('Eligible group for task1').selectOption('managers')
  await page.getByRole('button',{name:'Add milestone',exact:true}).click()
  await page.getByLabel('Name for item1',{exact:true}).fill('Review ready')
  await page.getByLabel('Start after for item1').selectOption('task1')
  await expectNoSeriousViolations(page,'Visual case model authoring')
  await page.getByRole('button',{name:'Use generated CMMN',exact:true}).click()
  await expect(page.getByLabel('Generated CMMN preview')).toHaveValue(/node_task1_item/)
  const generated=await page.getByLabel('Generated CMMN preview').inputValue()
  await page.getByRole('button',{name:'Create definition',exact:true}).click()
  await expect(page.getByRole('cell',{name:key,exact:true}).first()).toBeVisible()
  const downloading=page.waitForEvent('download')
  await page.getByRole('row').filter({has:page.getByRole('cell',{name:key,exact:true})}).getByRole('button',{name:'Export CMMN',exact:true}).click()
  const exported=await downloading
  expect(exported.suggestedFilename()).toBe(`${key}-v1.cmmn`)
  expect(await readFile((await exported.path())!,'utf8')).toBe(generated)
  page=await sessions.as('rhea.requester')
  await page.goto(`/w/${ws}/cases`)
  await page.getByRole('row').filter({has:page.getByRole('cell',{name:key,exact:true})}).getByRole('button',{name:'Start case',exact:true}).click()
  await expect(page).toHaveURL(new RegExp(`/w/${ws}/cases/[^/]+$`))
  const url=page.url()
  page=await sessions.as('mani.manager');await page.goto(url)
  await page.getByRole('button',{name:'Show case plan',exact:true}).click()
  await page.getByRole('button',{name:'Start task',exact:true}).click()
  await page.getByRole('dialog').getByLabel('Reason',{exact:true}).fill('Start the visually authored review')
  await page.getByRole('button',{name:'Confirm plan change',exact:true}).click()
  await page.getByRole('button',{name:'Complete task',exact:true}).click()
  await expect(page.getByText('completed',{exact:true}).first()).toBeVisible()
  await expect(page.getByText('Your work is complete. Further case details require current case read access.',{exact:true})).toBeVisible()
  page=await sessions.as('rhea.requester');await page.goto(url)
  await page.getByRole('button',{name:'Show case plan',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Achieved milestones',exact:true})).toBeVisible()
  await expect(page.getByText('Review ready',{exact:true}).last()).toBeVisible()
  await page.reload()
  await page.getByRole('button',{name:'Show case plan',exact:true}).click()
  await expect(page.getByText('Review ready',{exact:true}).last()).toBeVisible()
  await page.setViewportSize({width:390,height:844})
  await expectNoSeriousViolations(page,'Visually authored case mobile history')
})
