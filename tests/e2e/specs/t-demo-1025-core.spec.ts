const ex = path.resolve('../../examples/migration')
const tag = Date.now().toString(36)

async function analyse(page: Page, ws: string, file: string, format: string) {
  await page.goto(`/w/${ws}/migrations`)
  await page.getByLabel('Source format').selectOption(format)
  await page.getByLabel(/Source file/).setInputFiles(file)
  await page.getByRole('button', { name: 'Analyze source' }).click()
}

test('Camunda 7 purchase: import, map, convert, publish, run 4,999.99 vs 5,000', async ({ sessions }) => {
  const dana = await sessions.as('dana.designer')
  const ws = await workspaceId(dana)
  await analyse(dana, ws, path.join(ex, 'camunda7-purchase.bpmn'), 'bpmn')
  await expect(dana.getByRole('region', { name: 'Compatibility report' })).toBeVisible()
  await shot(dana, 'camunda-report')
  await axe(dana, 'camunda compatibility report')
  await dana.getByLabel('Map source assignment: source-managers').selectOption('managers')
  await dana.getByLabel('Map source assignment: source-finance').selectOption('finance-approvers')
  await dana.getByLabel('Target connection').selectOption('procurement')
  await dana.getByLabel('Target operation').selectOption('createOrder')
  await dana.getByRole('button', { name: 'Apply operation mapping' }).click()
  await expect(dana.getByLabel('Service task mappings (JSON)')).toHaveValue(/definitionVersion/)
  await dana.getByLabel('Workflow key', { exact: true }).fill(key('rh-camunda'))
  await dana.getByRole('checkbox', { name: /I reviewed the assumptions/ }).check()
  await shot(dana, 'camunda-form')
  await axe(dana, 'camunda mapping form')
  await dana.getByRole('button', { name: 'Convert to draft' }).click()
  await expect(dana.getByTestId('studio')).toBeVisible()
  await expect(dana.getByText(/Imported from camunda7/)).toBeVisible()
  await shot(dana, 'camunda-studio')
  await axe(dana, 'camunda studio')
  const id = dana.url().match(/workflows\/([0-9a-f-]+)/)![1]
  record('camunda import: convert to draft + studio banner', 'PASS')
  const pub = await sessions.as('paul.publisher')
  await pub.goto(`/w/${ws}/workflows/${id}/publish`)
  const ack = pub.getByRole('checkbox')
  for (let i = 0; i < await ack.count(); i++) if (await ack.nth(i).isVisible() && !(await ack.nth(i).isChecked())) await ack.nth(i).check()
  await pub.getByRole('button', { name: /Publish version \d+/ }).click()
  await expect(pub.getByTestId('publish-success')).toBeVisible({ timeout: 30_000 })
  record('camunda import: publish', 'PASS')
  const rq = await sessions.as('rhea.requester')
  const refs: Record<string, string> = {}
  for (const amt of ['4999.99', '5000']) {
    await rq.goto(`/w/${ws}/start/${id}`)
    await rq.locator('#req-title').fill(`Camunda ${amt} ${tag}`)
    await rq.locator('#req-costCenter').selectOption({ index: 1 })
    await rq.locator('#req-amount').fill(amt)
    const rest = await rq.locator('main input:visible, main select:visible').evaluateAll((els) => els.map((e) => (e as HTMLInputElement).id))
    record(`camunda start form fields (${amt})`, 'INFO', rest.join(','))
    await rq.getByRole('button', { name: 'Review request' }).click()
    await rq.getByRole('button', { name: 'Submit request' }).click()
    await expect(rq.getByRole('heading', { level: 1, name: 'Request submitted' })).toBeVisible()
    refs[amt] = (await rq.getByTestId('request-id').innerText()).trim()
  }
  const mgr = await sessions.as('mani.manager')
  for (const amt of ['4999.99', '5000']) {
    await mgr.goto(`/w/${ws}/tasks?view=claimable`)
    await mgr.getByRole('link', { name: `Camunda ${amt} ${tag}`, exact: true }).first().click()
    await expect(mgr.getByTestId('task-actions')).toBeVisible()
    const claim = mgr.getByRole('button', { name: 'Claim task' })
    if (await claim.isVisible()) await claim.click()
    await mgr.getByRole('button', { name: 'Approve', exact: true }).click()
    await expect(mgr.getByTestId('task-banner')).toContainText('You approved')
  }
  const fin = await sessions.as('fin.finance')
  await fin.goto(`/w/${ws}/tasks?view=claimable`)
  await fin.getByRole('link', { name: `Camunda 5000 ${tag}`, exact: true }).waitFor({ timeout: 30_000 }).catch(() => undefined)
  const finLinks = await fin.getByRole('link', { name: `Camunda 5000 ${tag}`, exact: true }).count()
  const finLinkSmall = await fin.getByRole('link', { name: `Camunda 4999.99 ${tag}`, exact: true }).count()
  record('camunda: 5,000 reaches finance, 4,999.99 does not', finLinks > 0 && finLinkSmall === 0 ? 'PASS' : 'FAIL', `finance sees 5000: ${finLinks}, 4999.99: ${finLinkSmall}`)
  const small = await sessions.as('rhea.requester')
  await small.goto(`/w/${ws}`)
  await small.getByRole('link', { name: refs['4999.99'] }).first().click()
  await expect(small.getByTestId('run-status')).toContainText(/Completed/, { timeout: 90_000 })
  const status = (await small.getByTestId('run-status').innerText()).replace(/\s+/g, ' ')
  const tl = (await small.getByTestId('timeline').innerText()).replace(/\s+/g, ' ').slice(0, 400)
  await shot(small, 'camunda-4999-run')
  await axe(small, 'camunda run 4999.99')
  record('camunda 4,999.99 completes without finance', 'PASS', `${status} | ${tl}`)
})

test('Camunda blockers: unsupported-features refused, xxe rejected unread', async ({ sessions }) => {
  sessions.allowHttpErrors()
  const dana = await sessions.as('dana.designer')
  const ws = await workspaceId(dana)
  await analyse(dana, ws, path.join(ex, 'unsupported-features.bpmn'), 'bpmn')
  await expect(dana.getByRole('region', { name: 'Compatibility report' })).toBeVisible()
  const text = await dana.locator('main').innerText()
  await shot(dana, 'camunda-unsupported')
  await axe(dana, 'camunda unsupported-features report')
  const blockers = (text.match(/\bblocker\b/gi) ?? []).length
  record('unsupported-features.bpmn: blockers listed', blockers > 1 ? 'PASS' : 'FAIL', `${blockers} mentions; timers/scripts/parallel: ${/timer/i.test(text)}/${/script/i.test(text)}/${/parallel/i.test(text)}`)
  await dana.getByLabel('Workflow key', { exact: true }).fill(key('rh-unsupf'))
  const acks = dana.getByRole('checkbox')
  for (let i = 0; i < await acks.count(); i++) if (await acks.nth(i).isVisible()) await acks.nth(i).check()
  const convert = dana.getByRole('button', { name: 'Convert to draft' })
  if (await convert.count()) {
    if (await convert.isEnabled()) await convert.click()
    await dana.waitForTimeout(2500)
  }
  record('unsupported-features.bpmn: conversion refused', /\/edit/.test(dana.url()) ? 'FAIL' : 'PASS', JSON.stringify(await dana.getByRole('alert').allInnerTexts()))
  await analyse(dana, ws, path.join(ex, 'xxe-attack.bpmn'), 'bpmn')
  await dana.waitForTimeout(2500)
  await shot(dana, 'camunda-xxe')
  const alert = JSON.stringify(await dana.getByRole('alert').allInnerTexts())
  const body = await dana.locator('main').innerText()
  record('xxe-attack.bpmn: rejected', /rejected|not allowed|unsafe|DOCTYPE|invalid|could not/i.test(alert + body) && !/root:|\[fonts\]|etc\/passwd/.test(body) ? 'PASS' : 'FAIL', alert)
  await axe(dana, 'xxe rejected')
})

