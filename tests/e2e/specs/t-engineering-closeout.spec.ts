test('real typed case data is authored, validated, corrected and retained after closure', async ({ sessions }) => {
  test.skip(MOCK, 'Requires real typed-data validation and protected history.')
  test.setTimeout(180_000)
  let page = await sessions.as('dana.designer')
  const ws = await workspaceId(page), key = uniq('typed-case')
  const sourceXml = readFileSync(new URL('../../../backend/app/src/test/resources/cases/manual-required.cmmn', import.meta.url), 'utf8').replaceAll('lifecycleCase', key)
  await newCaseType(page, ws, key)
  await useCmmnFile(page, `${key}.cmmn`, sourceXml)
  await addCaseField(page, 'summary', 'Summary', 'text', true)
  await addCaseField(page, 'amount', 'Amount', 'number', false)
  await checkAndPublish(page)
  page = await sessions.as('rhea.requester')
  await page.goto(`/w/${ws}/cases`)
  await page.getByRole('row').filter({ has: page.getByRole('cell', { name: key, exact: true }) }).getByRole('button', { name: 'Start case', exact: true }).click()
  const start = page.getByRole('dialog', { name: 'Start case', exact: true })
  await start.getByLabel(/^Summary/).fill('Original case evidence')
  await start.getByLabel('Amount', { exact: true }).fill('12.25')
  await start.getByRole('button', { name: 'Start case with data' }).click()
  await expect(page).toHaveURL(new RegExp(`/w/${ws}/cases/[^/]+$`))
  const url = page.url()
  await page.getByRole('button', { name: 'Show case data' }).click()
  await expect(page.getByLabel(/^Summary/)).toHaveValue('Original case evidence')
  await expect(page.getByRole('button', { name: 'Save case data' })).toHaveCount(0)
  page = await sessions.as('mani.manager')
  await page.goto(url)
  await page.getByRole('button', { name: 'Show case data' }).click()
  await page.getByLabel(/^Summary/).fill('Corrected case evidence')
  await page.getByLabel('Amount', { exact: true }).fill('20.5')
  await page.getByLabel('Reason for data change').fill('Reconciled the supporting evidence')
  await page.getByRole('button', { name: 'Save case data' }).click()
  await expect(page.getByText(/Case version 2/)).toBeVisible()
  await expect(page.getByLabel('Amount', { exact: true })).toHaveValue('20.5')
  await page.getByRole('button', { name: 'Show case plan' }).click()
  await page.getByRole('listitem').filter({ hasText: 'Required review' }).filter({ has: page.getByRole('button', { name: 'Start task', exact: true }) }).getByRole('button', { name: 'Start task', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Reason', { exact: true }).fill('Review corrected evidence')
  await page.getByRole('button', { name: 'Confirm plan change' }).click()
  await page.getByRole('button', { name: 'Complete task', exact: true }).click()
  await expect(page.getByText('No tasks are currently available.')).toBeVisible()
  page = await sessions.as('olga.operator')
  await page.goto(url)
  await page.getByRole('button', { name: 'Close case', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Reason', { exact: true }).fill('Required case work is complete')
  await page.getByRole('button', { name: 'Confirm change' }).click()
  await expect(page.getByText('Completed', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Show case data' }).click()
  await expect(page.getByLabel(/^Summary/)).toHaveValue('Corrected case evidence')
  await expect(page.getByRole('heading', { name: 'Data changes' })).toBeVisible()
  await expect(page.getByText('Original case evidence \u2192 Corrected case evidence', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Save case data' })).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await expectNoSeriousViolations(page, 'Typed case data and protected history after closure')
})
