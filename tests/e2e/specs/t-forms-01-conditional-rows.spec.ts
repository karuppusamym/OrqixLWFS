import { expect, test } from '../support/fixtures'
import { MOCK } from '../support/env'
import { apiGet, createPurchaseWorkflow, workspaceId, selectStep } from '../support/app'

test.describe('Conditional forms and repeating rows (mock API)', () => {
  test.skip(!MOCK, 'Fresh UI journey against the mock API; backend suites enforce pinned form rules')
  test('authors and publishes a conditional grouped form, submits typed rows and omits hidden old answers', async ({ sessions }) => {
    test.setTimeout(180_000)
    await sessions.mockCall('reset', { published: true, sampleRuns: false })
    let page = await sessions.as('dana.designer')
    const ws = await workspaceId(page)
    const wf = await createPurchaseWorkflow(page, ws)
    await page.goto(`/w/${ws}/workflows/${wf}/edit`)
    await page.getByRole('tab', { name: 'Steps', exact: true }).click()
    await selectStep(page, 'start')
    await page.getByRole('button', { name: 'Add a question' }).click()
    const notes = page.locator('[data-testid^="field-card-"]').last()
    await notes.getByLabel(/^Label/).fill('Extra notes')
    await notes.getByLabel(/^Label/).press('Enter')
    await notes.getByRole('checkbox', { name: 'Show only when a condition matches' }).check()
    await notes.getByLabel('Value to look at').selectOption('/input/amount')
    await notes.getByLabel('Comparison').selectOption('gte')
    await notes.getByLabel('Value', { exact: true }).fill('5000')
    await notes.getByLabel('Value', { exact: true }).press('Enter')
    await notes.getByRole('checkbox', { name: 'Require an answer when a condition matches' }).check()
    await notes.getByLabel('Value to look at').nth(1).selectOption('/input/amount')
    await notes.getByLabel('Comparison').nth(1).selectOption('gte')
    await notes.getByLabel('Value', { exact: true }).nth(1).fill('5000')
    await notes.getByLabel('Value', { exact: true }).nth(1).press('Enter')

    await page.getByRole('button', { name: 'Add a question' }).click()
    const lines = page.locator('[data-testid^="field-card-"]').last()
    await lines.getByLabel(/^Label/).fill('Order lines')
    await lines.getByLabel(/^Label/).press('Enter')
    await lines.getByLabel('Type', { exact: true }).selectOption('collection')
    await lines.getByLabel('Item type', { exact: true }).selectOption('object')
    await lines.getByRole('button', { name: 'Add row column' }).click()
    await lines.getByLabel('Column label').nth(1).fill('Quantity')
    await lines.getByLabel('Column label').nth(1).press('Enter')
    await lines.getByLabel('Column type').nth(1).selectOption('integer')
    await lines.getByRole('checkbox', { name: 'Required column Quantity' }).check()
    await page.getByRole('button', { name: 'Add form section' }).click()
    await page.getByLabel('Section title').fill('Supporting details')
    await page.getByLabel('Section title').press('Enter')
    await page.getByRole('checkbox', { name: 'Include Extra notes' }).check()
    await page.getByRole('checkbox', { name: 'Include Order lines' }).check()
    await page.getByLabel('Section columns').selectOption('2')
    await page.keyboard.press('Control+s')
    await expect(page.getByTestId('save-state')).toHaveText(/Saved/)
    const draft = await apiGet<{ revision: number; definition: { inputSchema: { properties: Record<string, { title: string }> } } }>(page, `/workspaces/${ws}/workflows/${wf}/draft`)
    const notesKey = Object.entries(draft.definition.inputSchema.properties).find(([, value]) => value.title === 'Extra notes')![0]
    const linesKey = Object.entries(draft.definition.inputSchema.properties).find(([, value]) => value.title === 'Order lines')![0]

    page = await sessions.as('paul.publisher')
    await page.goto(`/w/${ws}/workflows/${wf}/publish?revision=${draft.revision}`)
    const warnings = page.getByRole('checkbox', { name: /warnings/i })
    if (await warnings.isVisible()) await warnings.check()
    await page.getByRole('button', { name: /^Publish version/ }).click()
    await expect(page.getByRole('heading', { name: 'Version 1 published', exact: true })).toBeVisible()

    page = await sessions.as('rhea.requester')
    await page.goto(`/w/${ws}/start/${wf}`)
    await page.getByLabel('What are you buying?').fill('Row workflow test')
    await page.getByLabel('Business purpose').fill('Replacement')
    await page.getByLabel('Cost center').selectOption('IT')
    const amount = page.getByLabel('Amount (USD)')
    await amount.fill('5000')
    await expect(page.getByLabel(/Extra notes/)).toHaveAttribute('aria-required', 'true')
    await page.getByRole('button', { name: 'Review request', exact: true }).click()
    await expect(page.getByTestId('error-summary')).toContainText('Extra notes')
    await amount.fill('1800')
    await expect(page.getByTestId('error-summary')).toHaveCount(0)
    await amount.fill('5000')
    await page.getByLabel(/Extra notes/).fill('This answer must not be submitted after hiding')
    await page.getByRole('button', { name: 'Add Order lines row' }).click()
    await page.getByLabel(/Order lines, row 1: Name/).fill('Laptop')
    await page.getByLabel(/Order lines, row 1: Quantity/).fill('2')
    await amount.fill('1800')
    await expect(page.getByLabel(/Extra notes/)).toHaveCount(0)
    await page.getByRole('button', { name: 'Review request', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Check your request', exact: true })).toBeVisible()
    await expect(page.getByText('This answer must not be submitted after hiding')).toHaveCount(0)
    await expect(page.getByText(/Row 1: Name: Laptop; Quantity: 2/)).toBeVisible()
    await page.getByRole('button', { name: 'Submit request', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Request submitted', exact: true })).toBeVisible()
    const href = await page.getByRole('link', { name: 'View your request' }).getAttribute('href')
    const run = await apiGet<{ input: Record<string, unknown> }>(page, `/workspaces/${ws}/runs/${href!.split('/').at(-1)}`)
    expect(run.input).not.toHaveProperty(notesKey)
    expect(run.input[linesKey]).toEqual([{ name: 'Laptop', column2: 2 }])
  })
})
