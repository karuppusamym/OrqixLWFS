#!/usr/bin/env python3
"""Writes the SYNTHETIC blueprint sample PDF used by the Pega Blueprint import tests and demo (docs/build/S91).

The document is a generic application-blueprint outline written for Orqix. It is NOT a Pega export and does not
reproduce or claim compatibility with the layout of Pega's own Blueprint PDF. Pure standard library; output is
byte-for-byte deterministic (no dates or random identifiers).

Usage: python tools/blueprint-sample/make_synthetic_blueprint.py [output.pdf]
Default output: examples/migration/pega-blueprint/synthetic-blueprint.pdf
"""
import pathlib
import sys

PAGES = [
    [
        "SYNTHETIC SAMPLE - NOT A PEGA EXPORT",
        "Generated by tools/blueprint-sample for Orqix tests and demos. It imitates a generic",
        "application blueprint outline and does not reproduce the layout of Pega's Blueprint export.",
        "",
        "Case type: Equipment Purchase Request",
        "",
        "Stages",
        "- Submission",
        "- Review",
        "- Fulfilment",
        "",
        "Personas",
        "- Requester - submits purchase requests",
        "- Line Manager - approves every request",
        "- Finance Officer - approves requests of 5000 or more",
    ],
    [
        "Fields",
        "- Item description (text, required)",
        "- Amount (decimal, required)",
        "- Cost center (text, required)",
        "- Urgent (boolean, optional)",
        "",
        "Steps",
        "1. Manager approval (approval) - role: Line Manager; stage: Review; on reject: Rejected",
        "2. Finance approval (approval) - role: Finance Officer; stage: Review; then: Approved; on reject: Rejected",
    ],
    [
        "Decisions",
        "- Amount routing - after: Manager approval; if Amount >= 5000 then Finance approval; otherwise Approved",
        "",
        "SLAs",
        "- Manager approval: 2 days",
        "- Finance approval: 8",
        "",
        "Outcomes",
        "- Approved (success)",
        "- Rejected (rejected)",
        "",
        "Integrations",
        "- Purchase order export - target: none",
        "",
        "Notes",
        "Values in this sample are illustrative only.",
    ],
]


def escape(text: str) -> str:
    text.encode("ascii")  # Helvetica WinAnsi subset: keep the sample plain ASCII.
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def build() -> bytes:
    objects = []

    def add(body: bytes) -> int:
        objects.append(body)
        return len(objects)

    catalog = add(b"")  # placeholder, filled below
    pages_obj = add(b"")
    font = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>")
    page_ids = []
    for lines in PAGES:
        ops = ["BT", "/F1 9 Tf", "11 TL", "50 760 Td"]
        for line in lines:
            ops.append("(" + escape(line) + ") Tj T*")
        ops.append("ET")
        stream = ("\n".join(ops) + "\n").encode("ascii")
        content = add(b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"endstream")
        page_ids.append(add(("<< /Type /Page /Parent %d 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 %d 0 R >> >> /Contents %d 0 R >>"
                             % (pages_obj, font, content)).encode()))
    objects[catalog - 1] = ("<< /Type /Catalog /Pages %d 0 R >>" % pages_obj).encode()
    objects[pages_obj - 1] = ("<< /Type /Pages /Kids [%s] /Count %d >>" % (" ".join("%d 0 R" % p for p in page_ids), len(page_ids))).encode()
    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % number + body + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objects) + 1)
    for offset in offsets:
        out += b"%010d 00000 n \n" % offset
    out += b"trailer\n<< /Size %d /Root %d 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objects) + 1, catalog, xref)
    return bytes(out)


if __name__ == "__main__":
    target = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "examples/migration/pega-blueprint/synthetic-blueprint.pdf")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(build())
    print(f"wrote {target}")
